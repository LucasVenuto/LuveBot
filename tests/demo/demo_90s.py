def step8_vignette(browser):
    import base64
    logo = base64.b64encode((ROOT / 'docs/images/logo/luvebot-wordmark-white.svg').read_bytes()).decode()
    context = browser.new_context(viewport=SIZE, record_video_dir=str(OUT / 'vinheta'), record_video_size=SIZE)
    page = context.new_page()
    page.set_content(VIGNETTE.replace('{logo}', logo))
    page.wait_for_timeout(4500)
    video = page.video
    context.close()
    Path(video.path()).rename(OUT / 'vinheta-fecho.webm')
    log('VINHETA', 8, '"Seus Bots, seu servidor. LuveBot, by Luve." gerada pelo script depois do vídeo do app, em '
        'vinheta-fecho.webm: é vinheta, não é tela do app')


def main():
    ready()
    OUT.mkdir(parents=True, exist_ok=True)
    creds = credentials()
    with sync_playwright() as playwright:
        browser = playwright.chromium.launch(headless=True, args=['--no-sandbox'])
        login = browser.new_context(locale='pt-BR')
        response = login.request.post(DASHBOARD + '/auth/password-login', data={  # ONE login: Hermes answers 429 to more
            'provider': 'basic', 'username': creds['username'], 'password': creds['password'], 'next': '/'})
        assert response.status == 200 and response.json()['ok'] is True
        state = login.storage_state()
        login.close()
        context = browser.new_context(viewport=SIZE, storage_state=state, color_scheme='dark', locale='pt-BR',
                                      record_video_dir=str(OUT / 'app'), record_video_size=SIZE)
        assert context.request.put(DASHBOARD + '/api/dashboard/theme', data={'name': 'luve'}).status == 200
        themes = HOME / 'dashboard-themes'
        themes.mkdir(parents=True, exist_ok=True)
        (themes / 'luve.yaml').write_bytes((ROOT / 'theme/luve.yaml').read_bytes())  # what scripts/install.sh does
        drop_harness_vendas(context)
        page = context.new_page()
        failed = None
        try:
            step1_home(page)
            step2_bots(page, context)
            step3_room(page)
            step4_work_panel(page)
            step5_approvals(page, context)
            step6_handoff(page, context)
            step7_ceiling(page)
        except Exception as error:  # the video up to the failure is kept; the log says where it stopped
            failed = error
            page.screenshot(path=str(OUT / 'falha.png'))
            log('FALHOU', '-', f'{type(error).__name__}: {str(error)[:400]}')
        video = page.video
        context.close()
        Path(video.path()).rename(OUT / 'app.webm')
        if failed is None:
            step8_vignette(browser)
        browser.close()
    (OUT / 'demo.log').write_text('\n'.join(LOG) + '\n')
    if failed is not None:
        raise SystemExit(1)


if __name__ == '__main__':
    main()
