def send(page, text):
    box = page.get_by_label('Mensagem', exact=True)
    box.wait_for(timeout=UI)
    box.fill(text)
    box.press('Enter')


def step5_approvals(page, context):
    def draft(n):  # one session per run, like tests/invariants/test_approvals.py ask_run
        sid = api(context, 'POST', '/bots/vendas/sessions', {})['session']['id']
        return api(context, 'POST', '/bots/vendas/runs', {'input': f'Prepare o follow-up do lead {n}.', 'session_id': sid})['run']['id']
    runs = [draft(n) for n in range(1, DRAFTS + 1)]
    log('PREPARO', 5, f'{DRAFTS} rascunhos de follow-up pedidos à Vendas pela rota de runs do LuveBot (a mesma do chat)')
    pending = lambda: [a for a in api(context, 'GET', '/approvals?status=pending&limit=100')['approvals'] if a['run_id'] in runs]
    wait_for(lambda: len(pending()) == DRAFTS, 120, f'{DRAFTS} pending approvals')
    rail(page, 'Aprovações')
    page.get_by_role('button', name='Atualizar aprovações').click()
    cards = page.locator('[data-testid^="approval-card-"]')
    expect(cards).to_have_count(DRAFTS, timeout=UI)
    pause(page, 1500)
    page.get_by_label('Selecionar todas as pendentes').check()
    cards.last.get_by_role('checkbox').uncheck()  # the one that will be denied with a reason
    page.get_by_role('button', name='Permitir selecionados (uma vez)').click()
    page.get_by_role('button', name='Confirmar decisão em lote').click()
    expect(cards.filter(has=page.get_by_role('button', name='Negar…'))).to_have_count(1, timeout=60_000)
    log('OK', 5, f'{DRAFTS - 1} rascunhos aprovados em lote na caixa de aprovações')
    pause(page, 1200)
    cards.filter(has=page.get_by_role('button', name='Negar…')).get_by_role('button', name='Negar…').click()
    page.locator('#deny-reason-input').fill('Esse lead pediu para não receber mais e-mails.')
    pause(page, 900)
    page.get_by_role('button', name='Confirmar negação').click()
    wait_for(lambda: not pending(), 60, 'no pending approval left')
    log('OK', 5, '1 rascunho negado com motivo')
    log('LACUNA', 5, 'o Bot não corrige: o motivo fica no LuveBot e na auditoria, não chega ao Bot (reason_delivered=False) (b3, Brasa)')
    pause(page, 1500)


def step6_handoff(page, context):
    sidebar_bot(page, r'Engenheiro Dev|\bdev\b').click()
    send(page, 'Passe a correção para a Vendas avisar o cliente X.')
    expect(page.get_by_text('está com a Vendas no Kanban').first).to_be_visible(timeout=LIVE)
    edge = lambda: next((e for e in api(context, 'GET', '/map?window=7d').get('edges', []) if e['from'] == 'dev' and e['to'] == 'vendas'), None)
    wait_for(lambda: (edge() or {}).get('live'), 60, 'the live dev -> vendas edge')  # the watcher turns the Kanban task into a handoff
    rail(page, 'Mapa')
    page.locator('#tab-map-visual').click()
    pause(page, 3000)
    page.locator('#tab-map-accessible').click()
    expect(page.get_by_test_id('map-handoff-item').filter(has_text='Handoff ao vivo').first).to_be_visible(timeout=UI)
    log('OK', 6, 'Dev cria a tarefa da Vendas pelo Kanban do Hermes; o Mapa mostra a aresta dev -> vendas acesa')
    pause(page, 1500)


