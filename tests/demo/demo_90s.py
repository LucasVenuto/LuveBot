"""Launch demo (docs/PRODUCT_SPEC.md section 13), recorded in the INSTALLED app of the test harness: only what the app does today.

Runs inside the harness container, on a fresh `up` (it replaces the harness's `vendas` Bot with one made from the template):
  docker compose -f tests/harness/compose.yaml exec -T hermes python /root/.hermes/plugins/luvebot/tests/demo/demo_90s.py
Output in /fixtures/demo (on the host: /tmp/luvebot-harness/demo):
  app.webm            the app, recorded by Playwright (recordVideo), steps 1 to 7
  vinheta-fecho.webm  step 8, a CLOSING VIGNETTE generated by this script after the app video: it is NOT an app screen
  demo.log            one line per step: OK, LACUNA (a gap the app has today, never faked) or PREPARO (harness wiring, not product)
Only the model is fake (tests/harness/fake_openai.py, the t119 demo scenarios). Every product action is a click in the real UI;
PREPARO lines are the few things a person would do outside LuveBot (point a Bot at a model provider) or that only seed the demo.
"""
