def log(kind, step, text):
    line = f'{time.strftime("%H:%M:%S")} {kind:8s} passo {step}: {text}'
    LOG.append(line)
    print(line, flush=True)


def pause(page, ms=1200):
    page.wait_for_timeout(ms)  # time for a viewer to read the screen; never used to wait for the app


# ---- harness wiring through Hermes's and LuveBot's own routes (same calls as tests/invariants) ----
def csrf(context):
    return context.request.get(DASHBOARD + PREFIX + '/session').json()['csrf']


def api(context, method, path, body=None, plugin=True):
    url = DASHBOARD + (PREFIX if plugin else '') + path
    headers = {'X-LuveBot-CSRF': csrf(context)} if plugin and method != 'GET' else {}
    response = context.request.fetch(url, method=method, data=body, headers=headers)
    assert response.status < 300, f'{method} {path}: {response.status} {response.text()[:300]}'
    return response.json() if response.text() else {}


def wait_for(predicate, timeout, what):
    deadline = time.monotonic() + timeout
    while time.monotonic() < deadline:
        found = predicate()
        if found:
            return found
        time.sleep(1)
    raise TimeoutError(f'timed out waiting for {what}')


def wait_served(name, timeout=120):
    """The multiplexed gateway reloads a profile's plugins only once it serves it (tests/invariants/test_hook.py wait_served)."""
    from gateway.control_socket import reload_gateway_plugins
    wait_for(lambda: (reload_gateway_plugins(HOME, profile_home=HOME / 'profiles' / name) or {}).get('reloaded'), timeout,
             f'the gateway to serve {name}')


def drop_harness_vendas(context):
    """The harness entrypoint made a `vendas` profile; the demo makes its own from the Vendas template (same name)."""
    names = [p['name'] for p in context.request.get(DASHBOARD + '/api/profiles').json()['profiles']]
    if 'vendas' in names:
        assert context.request.delete(DASHBOARD + '/api/profiles/vendas').status < 300
        conn = sqlite3.connect(HOME / 'luvebot/luvebot.db')
        conn.execute('DELETE FROM bot_meta WHERE bot=?', ('vendas',))
        conn.commit()
        conn.close()
        log('PREPARO', 0, 'perfil vendas do harness removido pela rota do Hermes, para o template Vendas criar o seu')


def point_at_fake_model(context, name, kanban=False):
    """What a person does in Hermes to pick a model provider; here the provider is the harness's fake model, with the same
    config the harness gives its own profiles (tests/harness/entrypoint.py). Dev also gets Hermes's `kanban` toolset."""
    for key, value in (('OPENAI_BASE_URL', FAKE), ('OPENAI_API_KEY', 'harness')):
        api(context, 'PUT', '/api/env', {'key': key, 'value': value, 'profile': name}, plugin=False)
    api(context, 'PUT', '/api/config', {'profile': name, 'config': {
        'model': {'default': 'fake-harness', 'provider': 'custom', 'base_url': FAKE},
        'terminal': {'backend': 'local'}, 'approvals': {'mode': 'manual', 'timeout': 180},
        'platform_toolsets': {'api_server': ['terminal', 'kanban'] if kanban else ['terminal']}}}, plugin=False)
    wait_served(name)
    log('PREPARO', 2, f'{name}: provedor do modelo apontado para o modelo falso do harness (rotas /api/env e /api/config do Hermes)'
        + (', toolset kanban ligado' if kanban else ''))


# ---- the UI ----
def open_luvebot(page):
    page.goto(DASHBOARD + '/')
    page.locator('aside[aria-label="sidebar"]').wait_for(timeout=60_000)
    page.wait_for_function('() => !document.querySelector(\'[aria-label="Carregando bots"]\')', timeout=60_000)


def sidebar_bot(page, pattern):
    return page.locator('aside[aria-label="sidebar"] button[aria-pressed]').filter(has_text=re.compile(pattern, re.I)).first


def rail(page, label):
    page.get_by_role('navigation', name='Navegação Principal').get_by_role('button', name=re.compile(f'^{label}')).click()


def step1_home(page):
    open_luvebot(page)
    expect(page.locator('aside[aria-label="sidebar"]')).to_be_visible()
    log('OK', 1, 'o dashboard do Hermes abre direto no LuveBot (tab.override "/")')
    log('LACUNA', 1, 'o git clone não aparece: no harness o plugin é montado em /root/.hermes/plugins/luvebot; '
        'fora dele, quem liga o plugin é scripts/install.sh')
    pause(page, 2000)


def step2_bots(page, context):
    for label, name in TEMPLATES:
        page.locator('aside[aria-label="sidebar"]').get_by_label(re.compile('Novo Bot')).click()
        dialog = page.get_by_role('dialog')
        expect(dialog).to_contain_text('Passo 1 de 4', timeout=UI)
        dialog.get_by_role('button', name=re.compile(label)).first.click()
        pause(page, 700)
        for step in (2, 3):
            dialog.get_by_role('button', name='Avançar').click()
            expect(dialog).to_contain_text(f'Passo {step + 1} de 4', timeout=UI)
        # the model the harness's Hermes accepts in the wizard (tests/e2e/test_gate2.py); point_at_fake_model swaps the provider
        dialog.get_by_placeholder('claude-sonnet-5-5').fill('anthropic/claude-sonnet-4')
        with page.expect_response(lambda r: r.url.endswith(PREFIX + '/bots') and r.request.method == 'POST', timeout=120_000) as made:
            dialog.get_by_role('button', name='Criar Bot').click()
        assert made.value.status == 201, made.value.text()
        expect(dialog.get_by_test_id('bot-presentation')).to_contain_text('Bot criado com sucesso', timeout=UI)
        log('OK', 2, f'Bot {name} criado pelo template "{label}" no assistente (perfil real do Hermes)')
        # before the introduction (a real model run): the Bot must already talk to the harness's model
        point_at_fake_model(context, name, kanban=name == 'dev')
        intro = dialog.get_by_test_id('bot-introduction')
        intro.get_by_role('button', name='Pedir que o Bot se apresente').click(timeout=LIVE)  # the click confirms the cost
        expect(dialog.get_by_test_id('bot-introduction-answer')).to_contain_text(f'Oi, eu sou {label}', timeout=LIVE)
        log('OK', 2, f'{name} se apresenta de verdade (POST /bots/{name}/introduction, uma execução real no Hermes)')
        pause(page, 2500)
        dialog.get_by_role('button', name='Iniciar com este Bot').click()
        expect(dialog).to_have_count(0, timeout=UI)


