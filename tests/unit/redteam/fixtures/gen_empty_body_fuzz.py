#!/usr/bin/env python3
"""Generates empty-body-fuzz.json: bodies (after a fixed valid header) with the verdict the SERVER's classifier (backend/unicode_invisible.py + str.strip()) gives them, for the Vitest to hold the extractor
to (Lume, SK-6a; Prumo asked for a fuzz between the two classifiers). Deterministic: a seeded random generator and an alphabet written as code points. `--check` exits 1 unless the file is what this makes.

The oracle for a draft `HEADER + LF + body`: a refused character anywhere (the first one, with its line and column) -> hidden_characters; more than 50 marked -> too_many_invisible; a body that is
empty after the marked characters are taken out of a copy and the rest is stripped -> empty_body; else ok with the count and the positions of the marked characters."""
import importlib.util
import json
import random
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[4]
OUT = Path(__file__).with_name('empty-body-fuzz.json')
HEADER = '---\nname: enviar-relatorio\ndescription: Use quando precisar enviar o relatório semanal ao cliente.\n---'
ALPHABET = [0x61, 0x2e, 0x78, 0x20, 0x09, 0x0a, 0x0b, 0x0c, 0x1c, 0x1f, 0x85, 0xa0, 0xad, 0x34f, 0x61c, 0x1680, 0x2000, 0x2003, 0x200a, 0x200b, 0x200c, 0x200d, 0x200e, 0x2028, 0x2029, 0x202e, 0x202f,
            0x205f, 0x2060, 0x2066, 0x2800, 0x3000, 0x3164, 0x180e, 0xfe0e, 0xfe0f, 0xfeff, 0xfffe, 0x1f600, 0xe0041, 0x1d173, 0x0]           # letters, blanks of every kind, marked, refused, a visible emoji


def classifier():
    spec = importlib.util.spec_from_file_location('ui', ROOT / 'backend' / 'unicode_invisible.py')
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def verdict(ui, body):
    content = HEADER + '\n' + body
    seen = ui.scan(content)
    if seen['refused']:
        r = seen['refused']
        return {'ok': False, 'why': 'hidden_characters', 'details': {'code': f"U+{r['code_point']:04X}", 'line': r['line'], 'column': r['column']}}
    if seen['count'] > ui.MAX_MARKED:
        return {'ok': False, 'why': 'too_many_invisible', 'details': {'count': seen['count']}}
    if not ui.without_marked(body).strip():
        return {'ok': False, 'why': 'empty_body'}
    return {'ok': True, 'hidden': seen['count'], 'marks': [[m['code_point'], m['line'], m['column']] for m in seen['marked']]}


def cases():
    ui = classifier()
    rng = random.Random(20261030)
    bodies = ['']
    bodies += [chr(c) for c in ALPHABET] + [chr(c) * 3 for c in ALPHABET] + ['a' + chr(c) for c in ALPHABET] + [chr(c) + 'a' for c in ALPHABET]
    calm = [c for c in ALPHABET if ui.kind_of(c) != 'refuse']                              # most random strings must get past the refusals, or they all say the same word
    bodies += [chr(a) + chr(b) for a in calm for b in calm] + [chr(rng.choice(ALPHABET)) + chr(rng.choice(ALPHABET)) for _ in range(200)]
    bodies += [''.join(chr(rng.choice(calm if rng.random() < 0.93 else ALPHABET)) for _ in range(rng.randint(0, 10))) for _ in range(1500)]
    bodies += [chr(0x200c) * n for n in (49, 50, 51, 52)] + [chr(0x200c) * 50 + 'x', chr(0x200c) * 51 + chr(0xe0041), chr(0xe0041) + chr(0x200c) * 60]
    seen, out = set(), []
    for body in bodies:
        if body not in seen:
            seen.add(body)
            out.append({'body': body, 'expect': verdict(ui, body)})
    return out


def render():
    return json.dumps({'about': 'Generated by gen_empty_body_fuzz.py (Lume): bodies after a fixed valid header and the verdict of the server classifier; the Vitest holds the extractor to it.', 'header': HEADER, 'cases': cases()},
                      ensure_ascii=True, separators=(',', ':')) + '\n'


if __name__ == '__main__':
    text = render()
    if '--check' in sys.argv:
        sys.exit(0 if OUT.exists() and OUT.read_text() == text else 1)
    OUT.write_text(text)
    print(len(json.loads(text)['cases']), 'cases')
