export function formatString(
  str: string,
  params?: Record<string, string | number>
): string {
  if (!params) return str;
  return str.replace(/\{(\w+)\}/g, (match, key) =>
    params[key] !== undefined ? String(params[key]) : match
  );
}

export const STORAGE_KEY = "luvebot_locale";
export const LOCALE_EVENT = "luvebot_locale_change";

/**
 * Resolves the active locale:
 * 1. User preference from localStorage (safely with try/catch)
 * 2. Browser language (navigator.languages / navigator.language)
 * 3. Hermes SDK useI18n hook
 * 4. Fallback to "pt" if pt found, else "en"
 */
export function getInitialLocale(): Locale {
  // 1. User saved preference (highest priority)
  try {
    const storage =
      typeof window !== "undefined" && window.localStorage
        ? window.localStorage
        : typeof localStorage !== "undefined"
        ? localStorage
        : null;
    if (storage) {
      const saved = storage.getItem(STORAGE_KEY);
      if (saved === "pt" || saved === "en") {
        return saved;
      }
    }
  } catch {
    // localStorage might be unavailable/restricted
  }

  // 2. Browser language
  if (typeof navigator !== "undefined") {
    const langs = navigator.languages?.length ? navigator.languages : [navigator.language];
    for (const l of langs) {
      if (l && typeof l === "string") {
        const lower = l.toLowerCase();
        if (lower.startsWith("pt")) return "pt";
        if (lower.startsWith("en")) return "en";
      }
    }
  }

  // 3. Hermes SDK
  const sdk = getSDK();
  if (sdk?.useI18n) {
    try {
      const i18nResult = sdk.useI18n() as any;
      if (i18nResult?.locale && typeof i18nResult.locale === "string") {
        const lower = i18nResult.locale.toLowerCase();
        if (lower.startsWith("pt")) return "pt";
        if (lower.startsWith("en")) return "en";
      }
    } catch {
      // SDK hook error
    }
  }

  return "pt";
}

/**
 * Set user locale preference and notify all listeners.
 */
export function setLuveLocale(newLocale: Locale) {
  try {
    const storage =
      typeof window !== "undefined" && window.localStorage
        ? window.localStorage
        : typeof localStorage !== "undefined"
        ? localStorage
        : null;
    if (storage) {
      storage.setItem(STORAGE_KEY, newLocale);
    }
  } catch {
    // localStorage access denied
  }

  if (typeof window !== "undefined") {
    window.dispatchEvent(new CustomEvent(LOCALE_EVENT, { detail: newLocale }));
  }
}

/**
 * React hook for consuming translations and switching locales.
 */
export function useLuveI18n() {
  const [locale, setLocaleState] = React.useState<Locale>(() => getInitialLocale());

  React.useEffect(() => {
    if (typeof window === "undefined") return;

    const handleLocaleChange = (e: Event) => {
      const customEvent = e as CustomEvent<Locale>;
      if (customEvent.detail === "pt" || customEvent.detail === "en") {
        setLocaleState(customEvent.detail);
      } else {
        setLocaleState(getInitialLocale());
      }
    };

    window.addEventListener(LOCALE_EVENT, handleLocaleChange);
    return () => {
      window.removeEventListener(LOCALE_EVENT, handleLocaleChange);
    };
  }, []);

  const dict = translations[locale] || translations.pt;

  const t = React.useCallback(
    (key: TranslationKey, params?: Record<string, string | number>): string => {
      const str = dict[key] || translations.pt[key] || String(key);
      return formatString(str, params);
    },
    [dict]
  );

  const setLocale = React.useCallback((next: Locale) => {
    setLuveLocale(next);
  }, []);

  return { locale, t, setLocale };
}
